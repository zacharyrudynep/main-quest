// lib/companyFileGen.js — deterministic source generators for the company data
// files, used by the admin "save" API to rewrite lib/companiesData.js and
// lib/studios.js from edited data and commit them to the repo.
//
// These are PRETTY-PRINTERS of plain data structures — they do not decide shape.
// The admin/save layer converts its editable model into (companiesTree, studiosMap,
// tierMap) and hands them here. Keeping them pure + deterministic makes round-trips
// safe: serialize(parse(file)) is semantically identical to the original.

// Order company fields predictably: the four always-present ones first, then the
// known optional ones in a stable order, then any unknown passthrough keys last
// (so fields we don't explicitly manage — e.g. one-offs — are never dropped).
const FIELD_ORDER = [
  "name", "url", "email", "contact",
  "tier",
  "registerInterest", "registerInterestLink", "registerInterestSameAs",
  "emailApply", "emailSpecifics",
  "internship", "internshipLink", "internshipNote",
  "volunteer",
];

function jsString(s) {
  // Emit a double-quoted JS string literal, escaping what must be escaped.
  return '"' + String(s)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t") + '"';
}

function jsValue(v) {
  if (v === null) return "null";
  if (v === true) return "true";
  if (v === false) return "false";
  if (typeof v === "number") return String(v);
  return jsString(v);
}

// Render one company object as a single-line `{ key:val, ... }` literal, matching
// the existing file's compact style. Only includes keys that are present; unknown
// keys (not in FIELD_ORDER) are appended in their own insertion order.
function renderCompany(co) {
  const keys = [];
  for (const k of FIELD_ORDER) if (Object.prototype.hasOwnProperty.call(co, k)) keys.push(k);
  for (const k of Object.keys(co)) if (!FIELD_ORDER.includes(k)) keys.push(k);

  const parts = keys.map((k) => {
    // `name`, `url`, `email`, `contact` use "key: val" (space); the rest use the
    // tighter "key:val" the file uses for flags. Cosmetic only.
    const spaced = (k === "name" || k === "url" || k === "email" || k === "contact");
    return `${k}:${spaced ? " " : ""}${jsValue(co[k])}`;
  });
  return `{ ${parts.join(", ")} }`;
}

// companiesTree: { [country]: { [region]: Company[] } }
export function generateCompaniesData(companiesTree) {
  let out = "";
  out += "// lib/companiesData.js — the curated studio directory, moved out of pages/index.js\n";
  out += "// so the client, API routes, and the snapshot cron all share ONE source. Pure data.\n";
  out += "// Add new companies HERE going forward. (This file is generated by the admin\n";
  out += "// company editor at /admin/companies — hand-edits are fine but keep it pure data.)\n\n";
  out += "export const COMPANIES_DATA = {\n";

  const countries = Object.keys(companiesTree);
  countries.forEach((country, ci) => {
    out += `  ${jsString(country)}: {\n`;
    const regions = Object.keys(companiesTree[country]);
    regions.forEach((region, ri) => {
      const list = companiesTree[country][region] || [];
      out += `    ${jsString(region)}: [\n`;
      for (const co of list) out += `      ${renderCompany(co)},\n`;
      out += `    ],\n`;
    });
    out += `  },\n`;
  });

  out += "};\n";
  return out;
}

// studiosMap: { [companyName]: { platform, slug } }. Grouped by platform with a
// comment header per platform, matching the existing file's layout.
export function generateStudios(studiosMap) {
  let out = "";
  out += "// Single source of truth for the ATS studio registry.\n";
  out += "// Shared by the job board (pages/index.js) and the alert cron (pages/api/cron).\n";
  out += "// Format: \"Studio Name\": { platform, slug }\n";
  out += "// (Generated/maintained by the admin company editor at /admin/companies.)\n";
  out += "export const ATS_STUDIOS = {\n";

  // Group by platform, preserving first-seen platform order and first-seen name order.
  const byPlatform = {};
  const platformOrder = [];
  for (const [name, v] of Object.entries(studiosMap)) {
    const p = (v && v.platform) || "other";
    if (!byPlatform[p]) { byPlatform[p] = []; platformOrder.push(p); }
    byPlatform[p].push([name, v]);
  }
  // Longest name in the whole map sets the padding so colons line up like the original.
  const pad = Math.min(26, Math.max(0, ...Object.keys(studiosMap).map((n) => (jsString(n)).length)) + 1);

  platformOrder.forEach((p) => {
    out += `  // ─── ${p} ───\n`;
    for (const [name, v] of byPlatform[p]) {
      const key = jsString(name) + ":";
      out += `  ${key.padEnd(pad + 1, " ")} { platform:${jsString(v.platform)}, slug:${jsString(v.slug)} },\n`;
    }
  });

  out += "};\n";
  return out;
}